function generateDynamicZoneConfigs(themeName: string, artifacts: ThemeArtifact[]): ZoneConfig[] {
  const sortedEras = [...new Set(sortArtifactsByEra(artifacts).map(a => a.era))]

  const defaultZones: ZoneConfig[] = [
    { name: '源起', subtitle: `${themeName}的曙光`, timePeriod: sortedEras[0] || '远古', accentColor: '#8B7355', duration: '8分钟' },
    { name: '发展', subtitle: `${themeName}的繁荣`, timePeriod: sortedEras[Math.floor(sortedEras.length / 3)] || '中古', accentColor: '#B8860B', duration: '15分钟' },
    { name: '鼎盛', subtitle: `${themeName}的巅峰`, timePeriod: sortedEras[Math.floor(sortedEras.length * 2 / 3)] || '近古', accentColor: '#C41E3A', duration: '15分钟' },
    { name: '传承', subtitle: `${themeName}的延续`, timePeriod: '近现代', accentColor: '#708090', duration: '12分钟' },
    { name: '回响', subtitle: `${themeName}的当代启示`, timePeriod: '当代', accentColor: '#2F4F4F', duration: '8分钟' },
  ]

  return defaultZones
}

