// ============================================================
// 文物分组与组合说明生成
// ============================================================

function distributeArtifactsToZones(
  artifacts: ThemeArtifact[],
  zoneCount: number
): ThemeArtifact[][] {
  const sorted = sortArtifactsByEra(artifacts)
  const zones: ThemeArtifact[][] = Array.from({ length: zoneCount }, () => [])

  if (sorted.length === 0) return zones

  // 按时代均匀分配到各展区
  const perZone = Math.max(1, Math.ceil(sorted.length / zoneCount))
  sorted.forEach((artifact, idx) => {
    const zoneIdx = Math.min(Math.floor(idx / perZone), zoneCount - 1)
    zones[zoneIdx].push(artifact)
  })

  return zones
}

function generateArtifactReason(artifact: ThemeArtifact, themeName: string): string {
  if (artifact.significance) {
    return `${artifact.significance}，是${themeName}主题不可或缺的实物见证`
  }
  if (artifact.description) {
    return `${artifact.description}，为${themeName}主题提供了重要的实物支撑`
  }
  return `${artifact.name}作为${artifact.era}${artifact.category}类的代表文物，丰富了${themeName}的展陈维度`
}

function generateGroupNarrative(artifacts: ThemeArtifact[], zoneName: string, themeName: string): string {
  if (artifacts.length === 0) {
    return `本展区以文献与数字展项为主，通过多媒体手段呈现${zoneName}的核心内容。`
  }

  const names = artifacts.map(a => `「${a.name}」`).join('、')
  const eras = [...new Set(artifacts.map(a => a.era))].join('与')

  if (artifacts.length === 1) {
    return `${names}是${zoneName}的核心展品。它来自${eras}，以独特的物质形态和工艺特征，为${themeName}叙事提供了不可替代的实物锚点。单独展示并不意味着孤立——它与其他展区的文物形成跨时空的呼应，共同编织出完整的文明图景。`
  }

  if (artifacts.length === 2) {
    return `${names}两件文物构成${zoneName}的核心对话。它们分别来自${eras}，在材质、功能和时代背景上形成互补：一件呈现制度的框架，一件展现技术的细节，合而观之，方见${zoneName}的全貌。`
  }

  // 三件以上
  const levels = artifacts.filter(a => a.level).map(a => a.level)
  const levelDesc = levels.length > 0 ? `涵盖了${[...new Set(levels)].join('、')}等级别` : '涵盖了不同等级'
  const categories = [...new Set(artifacts.map(a => a.category))]

  return `${names}构成${zoneName}的核心文物群。这组文物跨越${eras}，${levelDesc}，涉及${categories.join('、')}等领域，从制度、技术和生活三个维度立体呈现了${zoneName}的历史图景。它们之间的对话关系尤为值得关注：${artifacts[0].name}确立了时代的制度框架，${artifacts.length > 1 ? artifacts[1].name : ''}提供了技术实证，${artifacts.length > 2 ? artifacts.slice(2).map(a => a.name).join('、') + '则' : '则'}丰富了日常生活的细节——制度、技术、生活三重叙事在此交汇，方能见出${themeName}的深层脉络。`
}

