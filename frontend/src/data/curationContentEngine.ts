function generateDynamicNarratives(
  themeName: string,
  zoneConfigs: ZoneConfig[],
  artifacts: ThemeArtifact[]
): string[] {
  const sorted = sortArtifactsByEra(artifacts)

  return zoneConfigs.map((config, idx) => {
    const eraArtifacts = sorted.filter((_, i) => Math.floor(i / Math.max(1, Math.ceil(sorted.length / zoneConfigs.length))) === idx)
    const artifactDesc = eraArtifacts.length > 0
      ? `本展区汇集了${eraArtifacts.map(a => `「${a.name}」`).join('、')}等珍贵文物，`
      : ''

    return `${config.name}——${config.subtitle}。

${config.timePeriod}，${themeName}的发展进入了新的阶段。${artifactDesc}从这些文物中，我们可以清晰地看到${themeName}在技术、制度和文化层面的演进轨迹。每一件文物都是一个时代的缩影，它们共同构成了${themeName}叙事的重要章节。

考古发现与文献研究为我们还原了这一时期的历史图景。${themeName}的发展不是孤立的事件，而是与政治、经济、文化的整体变迁紧密相连。正如学者所言，理解${themeName}，就是理解中华文明演进的一个关键维度。`
  })
}

