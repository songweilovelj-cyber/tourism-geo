// 时间轴数据生成
// ============================================================

function generateTimeline(artifacts: ThemeArtifact[], themeName: string): TimelineEntry[] {
  const sorted = sortArtifactsByEra(artifacts)
  const eraGroups = new Map<string, ThemeArtifact[]>()

  // 按时代分组
  for (const artifact of sorted) {
    const era = artifact.era
    if (!eraGroups.has(era)) {
      eraGroups.set(era, [])
    }
    eraGroups.get(era)!.push(artifact)
  }

  // 生成时间轴条目
  const entries: TimelineEntry[] = []

  for (const [era, groupArtifacts] of eraGroups) {
    const year = ERA_YEAR_MAP[era] || era

    // 根据主题生成事件描述
    const event = generateTimelineEvent(era, groupArtifacts, themeName)

    entries.push({
      year,
      era,
      event,
      artifacts: groupArtifacts.map(a => a.name),
    })
  }

  return entries
}

