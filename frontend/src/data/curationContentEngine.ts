// ============================================================
// 主函数
// ============================================================

export function generateCurationContent(
  themeId: string,
  themeName: string,
  selectedArtifacts: ThemeArtifact[],
  keyDimensions?: string[]
): CurationContent {
  const normalizedName = normalizeThemeName(themeName)

  // 获取展区配置，若未预设则动态生成
  const zoneConfigs = ZONE_CONFIGS[normalizedName] || generateDynamicZoneConfigs(themeName, selectedArtifacts)

  // 将文物分配到各展区
  const artifactDistributions = distributeArtifactsToZones(selectedArtifacts, zoneConfigs.length)

  // 获取叙事文案库，若未预设则生成通用叙事
  const narratives = NARRATIVE_LIBRARY[normalizedName] || generateDynamicNarratives(themeName, zoneConfigs, selectedArtifacts)

  // 构建展区
  const zones: CuratedZone[] = zoneConfigs.map((config, idx) => {
    const zoneArtifacts = artifactDistributions[idx] || []
    const promptKey = normalizedName
    const promptList = IMAGE_PROMPTS[promptKey] || IMAGE_PROMPTS['default']
    const imagePrompt = promptList[Math.min(idx, promptList.length - 1)] || promptList[promptList.length - 1]

    return {
      zoneNumber: idx + 1,
      name: config.name,
      subtitle: config.subtitle,
      timePeriod: config.timePeriod,
      narrative: narratives[idx] || `${config.name}：${config.subtitle}。本展区聚焦${config.timePeriod}的历史脉络，通过精选文物与深度叙事，呈现${themeName}的文明图景。`,
      artifactGroup: {
        artifacts: zoneArtifacts.map(a => ({
          id: a.id,
          name: a.name,
          reason: generateArtifactReason(a, themeName),
        })),
        groupNarrative: generateGroupNarrative(zoneArtifacts, config.name, themeName),
      },
      spatialHint: (SPATIAL_HINTS[normalizedName] || SPATIAL_HINTS['default'])?.[idx] || '建议采用主题式空间布局，配合多媒体互动展项。',
      lightingMood: (LIGHTING_MOODS[normalizedName] || LIGHTING_MOODS['default'])?.[idx] || '柔和的暖白光聚焦展品，四周保持适度暗场。',
      imagePrompt,
      imageUrl: buildImageUrl(imagePrompt),
      educationGoal: (EDUCATION_GOALS[normalizedName] || EDUCATION_GOALS['default'])?.[idx] || `理解${config.name}在${themeName}主题中的核心地位与历史价值。`,
      duration: config.duration,
      accentColor: config.accentColor,
    }
  })

  // 生成时间轴数据
  const timeline = generateTimeline(selectedArtifacts, themeName)

  // 封面
  const coverPrompt = COVER_PROMPTS[normalizedName] || COVER_PROMPTS['default']

  // 策展人陈述
  const curatorStatement = CURATOR_STATEMENTS[normalizedName] || CURATOR_STATEMENTS['default']

  // 展览亮点
  const highlights = EXHIBITION_HIGHLIGHTS[normalizedName] || EXHIBITION_HIGHLIGHTS['default']

  return {
    zones,
    timeline,
    coverImagePrompt: coverPrompt,
    coverImageUrl: buildImageUrl(coverPrompt),
    curatorStatement,
    exhibitionHighlights: highlights,
  }
}

