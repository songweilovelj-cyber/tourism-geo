function getEraSortKey(era: string): number {
  // 精确匹配
  if (ERA_SORT_ORDER[era] !== undefined) return ERA_SORT_ORDER[era]
  // 模糊匹配：取最长匹配
  let bestKey = 9999
  for (const [key, val] of Object.entries(ERA_SORT_ORDER)) {
    if (era.includes(key) && key.length > 0) {
      if (Math.abs(val) < Math.abs(bestKey) || bestKey === 9999) {
        bestKey = val
      }
    }
  }
  return bestKey
}

function sortArtifactsByEra(artifacts: ThemeArtifact[]): ThemeArtifact[] {
  return [...artifacts].sort((a, b) => getEraSortKey(a.era) - getEraSortKey(b.era))
}

